-- 여기에 저장하고 조회는 이 값만 읽는다.
-- [형식] JSON 배열의 배열: [[1, 512.0], [2, 498.5], ...]. 파워가 없는 활동은 지표 행이 없고, 이 열이 생기기 전에 저장한
-- 행은 NULL이다(조회할 때 샘플로 계산한다).
